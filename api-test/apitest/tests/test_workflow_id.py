    @pytest.mark.workflow_id_bo
    @pytest.mark.parametrize('workflow_id_bo, status_code', test_data_bo)
    def test_workflow_id_bo_existed(self, user, workflow_id_bo, status_code):
        helper = NeptuneHelper(user)
        data = {
            "workflowid": workflow_id_bo,
            "lang": "en",
            "token": user.auth_token,
            "fields": {
                "account_name": "123"
            }
        }
        rs = helper.execute_workflow_status_code(data, status_code)
        actual_status = rs['status']
        description = rs['description']
        assert rs, f"Empty response"
        assert actual_status==expected_status, f'Description: \'{description}\'. Expected \'{expected_status}\', Actual \'{actual_status}\'.'
    
